#!/usr/bin/env python3
"""Generates the launcher / notification icons (vector drawables) and PNG previews.

Original artwork: a speaker whose cone is a folded-paper dart, sound waves, and an "UNOFFICIAL" ribbon
(text as outlines from DejaVu Sans Bold, cut out of the ribbon). Not Telegram's logo.
Usage: python3 tools/icon/generate_icon.py [preview_dir]
"""
import os, subprocess, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "app/src/main/res/drawable")
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
BLUE_TOP, BLUE_BOTTOM = "#3DB6EC", "#1A86C7"

# --- Shapes on the 108 x 108 adaptive-icon canvas (safe zone: circle r=33 around 54,54) -------------------
# Speaker body + cone shaped like a folded paper dart pointing right (fold line cut out, evenOdd)
SPEAKER = ("M30,45 L38,45 L54,33 Q57,31.5 57,35 L57,73 Q57,76.5 54,75 L38,63 L30,63 Q27,63 27,60 L27,48 Q27,45 30,45 Z "
           # the fold: a thin slit from the cone's tip toward its base
           "M40,54.8 L55,41 L55,44 L42.6,54.8 Z")
def arc(r, w, a=38):
    import math
    cx, cy = 58, 54
    t = math.radians(a)
    x1, y1 = cx + r*math.cos(t), cy - r*math.sin(t)
    x2, y2 = cx + r*math.cos(t), cy + r*math.sin(t)
    ri = r - w
    x3, y3 = cx + ri*math.cos(t), cy + ri*math.sin(t)
    x4, y4 = cx + ri*math.cos(t), cy - ri*math.sin(t)
    f = lambda v: f"{v:.2f}"
    return (f"M{f(x1)},{f(y1)} A{r},{r} 0 0,1 {f(x2)},{f(y2)} A{w/2},{w/2} 0 0,1 {f(x3)},{f(y3)} "
            f"A{ri},{ri} 0 0,0 {f(x4)},{f(y4)} A{w/2},{w/2} 0 0,1 {f(x1)},{f(y1)} Z")
WAVES = arc(9, 3.6, 40) + " " + arc(16, 3.6, 40) + " " + arc(23, 3.6, 38)

def text_path(text, x_center, baseline, height):
    font = TTFont(FONT)
    gs = font.getGlyphSet(); cmap = font.getBestCmap(); upm = font["head"].unitsPerEm
    cap = getattr(font["OS/2"], "sCapHeight", 0) or 0.73 * upm
    s = height / cap
    width = sum(gs[cmap[ord(c)]].width for c in text) * s
    x = x_center - width / 2
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.2f}")
    for c in text:
        g = gs[cmap[ord(c)]]
        g.draw(TransformPen(pen, (s, 0, 0, -s, x, baseline)))
        x += g.width * s
    return pen.getCommands(), width

# Ribbon across the lower part of the safe zone; the text is cut out of it
TEXT, TEXT_W = text_path("UNOFFICIAL", 54, 78.1, 4.2)
RIB_W = TEXT_W + 6
_l, _r, _t, _b = 54 - RIB_W/2, 54 + RIB_W/2, 72.6, 80.2
RIBBON = (f"M{_l+2:.2f},{_t} L{_r-2:.2f},{_t} Q{_r:.2f},{_t} {_r:.2f},{_t+2} L{_r:.2f},{_b-2} Q{_r:.2f},{_b} {_r-2:.2f},{_b} "
          f"L{_l+2:.2f},{_b} Q{_l:.2f},{_b} {_l:.2f},{_b-2} L{_l:.2f},{_t+2} Q{_l:.2f},{_t} {_l+2:.2f},{_t} Z")

def shift(path, dy):  # move speaker+waves up so the ribbon fits in the safe zone
    return path
GLYPH = SPEAKER + " " + WAVES

def vector(paths, size=108, viewport=108, tint=None, extra_ns=False):
    ns = 'xmlns:android="http://schemas.android.com/apk/res/android"' + (' xmlns:aapt="http://schemas.android.com/aapt"' if extra_ns else "")
    body = "\n".join(paths)
    t = f'\n    android:tint="{tint}"' if tint else ""
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icon/generate_icon.py; edit the script, not this file -->\n'
            f'<vector {ns}\n    android:width="{size}dp"\n    android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}"{t}>\n{body}\n</vector>\n')

def p(d, color="#FFFFFFFF", even_odd=False, translate=None):
    fill = '\n        android:fillType="evenOdd"' if even_odd else ""
    return f'    <path\n        android:fillColor="{color}"{fill}\n        android:pathData="{d}" />'

GLYPH_SCALE = 0.78
def group(inner, dy):
    return f'    <group android:pivotX="54" android:pivotY="54" android:scaleX="{GLYPH_SCALE}" android:scaleY="{GLYPH_SCALE}" android:translateY="{dy}">\n' + inner.replace("\n    ", "\n        ").replace("    <path", "        <path", 1) + "\n    </group>"

GLYPH_DY = -6  # lift the speaker so it and the ribbon share the safe zone
FG = [group(p(GLYPH, even_odd=True), GLYPH_DY), p(RIBBON + " " + TEXT, even_odd=True)]
BG = ['    <path android:pathData="M0,0h108v108h-108z">\n        <aapt:attr name="android:fillColor">\n'
      '            <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108">\n'
      f'                <item android:offset="0" android:color="{BLUE_TOP}" />\n'
      f'                <item android:offset="1" android:color="{BLUE_BOTTOM}" />\n'
      '            </gradient>\n        </aapt:attr>\n    </path>']

# Notification small icon (24 dp, white on transparent): the speaker + waves only, scaled from the 108 canvas
NOTIF = f'    <group android:scaleX="0.36" android:scaleY="0.36" android:translateX="-7.3" android:translateY="-7.44">\n' \
        f'        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{GLYPH}" />\n    </group>'

def main():
    def write(name, text):
        with open(os.path.join(RES, name), "w") as f: f.write(text)

    write("ic_launcher_foreground.xml", vector(FG))
    write("ic_launcher_monochrome.xml", vector(FG))
    write("ic_launcher_background.xml", vector(BG, extra_ns=True))
    # Splash (AndroidX SplashScreen): the blue disc with the speaker, no ribbon
    SPLASH = [p("M22,54 a32,32 0 1,0 64,0 a32,32 0 1,0 -64,0 Z", "#FF2A9FDA"), group(p(GLYPH, even_odd=True), 0)]
    write("ic_splash.xml", vector(SPLASH))
    write("ic_notification.xml", vector([NOTIF], size=24, viewport=24))

    # --- Previews ---------------------------------------------------------------------------------------------
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build/icon-preview")
    os.makedirs(out, exist_ok=True)
    def svg_icon(mask, mono=False, px=432):
        bg = ('<rect width="108" height="108" fill="#E8EEF3"/>' if mono else
              f'<defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{BLUE_TOP}"/>'
              f'<stop offset="1" stop-color="{BLUE_BOTTOM}"/></linearGradient></defs><rect width="108" height="108" fill="url(#g)"/>')
        fg = "#2E5A73" if mono else "#FFFFFF"
        clip = {"round": '<circle cx="54" cy="54" r="36"/>',
                "squircle": '<path d="M54,18 C83,18 90,25 90,54 C90,83 83,90 54,90 C25,90 18,83 18,54 C18,25 25,18 54,18 Z"/>'}[mask]
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{px}" height="{px}" viewBox="18 18 72 72">'
                f'<clipPath id="m">{clip}</clipPath><g clip-path="url(#m)">{bg}'
                f'<path transform="translate(0,{GLYPH_DY}) translate(54,54) scale({GLYPH_SCALE}) translate(-54,-54)" fill="{fg}" fill-rule="evenodd" d="{GLYPH}"/>'
                f'<path fill="{fg}" fill-rule="evenodd" d="{RIBBON} {TEXT}"/></g></svg>')
    def notification_svg():
        small = f'<svg x="22" y="30" width="28" height="28" viewBox="27 27 54 54"><path transform="translate(0,0)" fill="#5f6368" fill-rule="evenodd" d="{GLYPH}"/></svg>'
        large = f'<svg x="560" y="56" width="120" height="120" viewBox="18 18 72 72"><clipPath id="c"><circle cx="54" cy="54" r="36"/></clipPath><g clip-path="url(#c)"><defs><linearGradient id="g2" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{BLUE_TOP}"/><stop offset="1" stop-color="{BLUE_BOTTOM}"/></linearGradient></defs><rect width="108" height="108" fill="url(#g2)"/><path transform="translate(0,{GLYPH_DY}) translate(54,54) scale({GLYPH_SCALE}) translate(-54,-54)" fill="#fff" fill-rule="evenodd" d="{GLYPH}"/><path fill="#fff" fill-rule="evenodd" d="{RIBBON} {TEXT}"/></g></svg>'
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="720" height="260"><rect width="720" height="260" rx="28" fill="#F1F3F4"/>{small}'
                f'<text x="60" y="50" font-family="sans-serif" font-size="20" fill="#5f6368">Narri · Reading</text>'
                f'<text x="24" y="104" font-family="sans-serif" font-size="30" font-weight="bold" fill="#202124">News chat</text>'
                f'<text x="24" y="140" font-family="sans-serif" font-size="24" fill="#5f6368">From Dana</text>{large}'
                f'<g fill="#202124"><rect x="40" y="196" width="22" height="22" rx="3"/><polygon points="170,190 196,207 170,224"/>'
                f'<rect x="300" y="190" width="9" height="34"/><rect x="318" y="190" width="9" height="34"/>'
                f'<polygon points="430,190 452,207 430,224"/><rect x="454" y="190" width="6" height="34"/></g></svg>')
    files = {"launcher_round": svg_icon("round"), "launcher_squircle": svg_icon("squircle"),
             "launcher_themed_monochrome": svg_icon("round", mono=True), "notification": notification_svg()}
    for name, svg in files.items():
        html = os.path.join(out, name + ".html")
        w, h = (720, 260) if name == "notification" else (432, 432)
        with open(html, "w") as f: f.write(f"<html><body style='margin:0;background:transparent'>{svg}</body></html>")
        subprocess.run(["google-chrome", "--headless=new", "--no-sandbox", "--disable-gpu", "--hide-scrollbars",
                        "--default-background-color=00000000", f"--window-size={w},{h}",
                        f"--screenshot={os.path.join(out, name + '.png')}", "file://" + html],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        os.remove(html)
    print("ok", out)


if __name__ == "__main__":
    main()
