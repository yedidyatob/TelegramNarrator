#!/usr/bin/env python3
"""Generates EdgeVoiceMap.kt (#89) from Edge's public voice list.

Usage: python3 tools/edge/generate_voice_map.py [voices.json] > \
  app/src/main/java/io/github/yedidyatob/telegramnarrator/domain/edge/EdgeVoiceMap.kt
Without a file argument the list is downloaded from the Edge read-aloud endpoint.
For every language: one male and one female voice, from the language's main locale when it has one.
"""
import json, sys, urllib.request

URL = ("https://speech.platform.bing.com/consumer/speech/synthesize/readaloud/voices/list"
       "?trustedclienttoken=6A5AA1D4EAFF4E9FB37E23D68491D6F4")
# Main locale for languages whose obvious "LANG-LANG" region doesn't exist or isn't the usual choice
PREFERRED = {
    "en": "en-US", "pt": "pt-BR", "zh": "zh-CN", "ar": "ar-SA", "he": "he-IL", "ko": "ko-KR", "ja": "ja-JP",
    "hi": "hi-IN", "uk": "uk-UA", "sv": "sv-SE", "da": "da-DK", "el": "el-GR", "cs": "cs-CZ", "es": "es-ES",
    "fr": "fr-FR", "de": "de-DE", "it": "it-IT", "ru": "ru-RU", "nl": "nl-NL", "fa": "fa-IR", "ur": "ur-PK",
    "bn": "bn-IN", "ta": "ta-IN", "sw": "sw-KE", "ms": "ms-MY", "vi": "vi-VN", "sr": "sr-RS", "ga": "ga-IE",
    "kk": "kk-KZ", "et": "et-EE", "sl": "sl-SI", "ca": "ca-ES", "eu": "eu-ES", "gl": "gl-ES", "af": "af-ZA",
    "zu": "zu-ZA", "sq": "sq-AL", "hy": "hy-AM", "ka": "ka-GE", "ne": "ne-NP", "si": "si-LK", "km": "km-KH",
    "lo": "lo-LA", "my": "my-MM", "mn": "mn-MN", "ps": "ps-AF", "so": "so-SO", "jv": "jv-ID", "su": "su-ID",
    "fil": "fil-PH", "nb": "nb-NO", "cy": "cy-GB", "is": "is-IS", "mk": "mk-MK", "mt": "mt-MT", "uz": "uz-UZ",
    "az": "az-AZ", "bs": "bs-BA", "lt": "lt-LT", "lv": "lv-LV", "hr": "hr-HR", "ro": "ro-RO", "hu": "hu-HU",
    "pl": "pl-PL", "fi": "fi-FI", "tr": "tr-TR", "th": "th-TH", "id": "id-ID", "bg": "bg-BG", "sk": "sk-SK",
}
# The app's multilingual voices stay the English choice (they also read other languages well)
OVERRIDES = {"en": ("en-US-AndrewMultilingualNeural", "en-US-AvaMultilingualNeural")}


def main():
    data = json.load(open(sys.argv[1])) if len(sys.argv) > 1 else json.load(urllib.request.urlopen(URL, timeout=30))
    by_lang = {}
    for v in data:
        lang = v["Locale"].split("-")[0].lower()
        by_lang.setdefault(lang, []).append(v)
    rows = []
    for lang in sorted(by_lang):
        if lang in OVERRIDES:
            rows.append((lang,) + OVERRIDES[lang]); continue
        voices = by_lang[lang]
        main_locale = PREFERRED.get(lang, f"{lang}-{lang.upper()}")
        def pick(gender):
            cands = [v for v in voices if v["Gender"] == gender]
            cands.sort(key=lambda v: (v["Locale"] != main_locale, "Multilingual" in v["ShortName"], v["Locale"], v["ShortName"]))
            return cands[0]["ShortName"] if cands else None
        rows.append((lang, pick("Male"), pick("Female")))
    out = sys.stdout
    out.write("package io.github.yedidyatob.telegramnarrator.domain.edge\n\n")
    out.write("// GENERATED by tools/edge/generate_voice_map.py from Edge's voice list. Do not edit by hand.\n\n")
    out.write("/** Edge voice per language (ISO 639 code): male to female; null when Edge has none of that gender. */\n")
    out.write("internal object EdgeVoiceMap {\n    val VOICES: Map<String, Pair<String?, String?>> = mapOf(\n")
    for lang, m, f in rows:
        q = lambda s: f'"{s}"' if s else "null"
        out.write(f'        "{lang}" to ({q(m)} to {q(f)}),\n')
    out.write("    )\n}\n")


main()
